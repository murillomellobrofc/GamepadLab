// Builds the controller drawings the UI animates from Zacksly's original art
// (apps/ui/public/controllers/<family>/source, CC BY 3.0, see ASSETS_LICENSE.md):
// gives every part the ID the frontend drives (btn-cross, stick-left,
// trigger-l2, touchpad…), drops the embedded colours so the app theme paints
// it, crops the canvas, groups glyphs with their buttons and adds a few parts
// of GamepadLab's own (trigger gauges, D-pad arms, touch points, paddles).
// Run after changing a source drawing: node scripts/build-controller-art.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const ROOT = 'apps/ui/public/controllers';
const GEOMETRY = [
  'd',
  'cx',
  'cy',
  'r',
  'rx',
  'ry',
  'x',
  'y',
  'width',
  'height',
  'x1',
  'y1',
  'x2',
  'y2',
  'points',
  'transform',
];

/** Drawable elements of the source, in document order, with their stroke width. */
function readSource(path) {
  const svg = readFileSync(path, 'utf8');
  const widths = {};
  const style = svg.match(/<style>([\s\S]*?)<\/style>/)?.[1] ?? '';
  for (const [, selectors, body] of style.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
    const w = body.match(/stroke-width:\s*([\d.]+)/)?.[1];
    if (!w) continue;
    for (const sel of selectors.split(',')) widths[sel.trim().replace(/^\./, '')] = w;
  }
  const body = svg.slice(svg.indexOf('</defs>'));
  return [...body.matchAll(/<(path|circle|line|polygon|polyline|rect|ellipse)\b([^>]*?)\/?>/g)].map(
    ([, tag, attrs]) => {
      const a = Object.fromEntries(
        [...attrs.matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]),
      );
      return { tag, a, width: widths[a.class] };
    },
  );
}

function draw(el, role, indent) {
  const geo = GEOMETRY.filter((k) => el.a[k] != null).map((k) => `${k}="${el.a[k]}"`);
  const width = el.width && role !== 'glyph-fill' ? ` stroke-width="${el.width}"` : '';
  return `${indent}<${el.tag} class="gl-${role}" ${geo.join(' ')}${width}/>`;
}

/** Layout items: [id|null, [[index, role], …]] or a raw SVG string. */
function build(family) {
  const src = readSource(`${ROOT}/${family.source}`);
  if (src.length !== family.count) {
    throw new Error(`${family.source}: expected ${family.count} elements, found ${src.length}`);
  }
  const used = new Set();
  const lines = [];
  for (const item of family.layout) {
    if (typeof item === 'string') {
      lines.push(item.replace(/^/gm, '  '));
      continue;
    }
    const [id, parts, extra = ''] = item;
    const children = parts.map(([i, role]) => {
      used.add(i);
      return draw(src[i], role, id ? '    ' : '  ');
    });
    if (!id) lines.push(...children);
    else
      lines.push(
        `  <g id="${id}">`,
        ...children,
        ...(extra ? [extra.replace(/^/gm, '    ')] : []),
        '  </g>',
      );
  }
  const dropped = src.map((_, i) => i).filter((i) => !used.has(i));
  const unexpected = dropped.filter((i) => !(family.drop ?? []).includes(i));
  if (unexpected.length)
    throw new Error(`${family.out}: elements not placed: ${unexpected.join(', ')}`);
  const out = `<?xml version="1.0" encoding="UTF-8"?>
<!--
  ${family.title} for GamepadLab.
  Based on "${family.credit}" by Zacksly (https://zacksly.itch.io),
  licensed under CC BY 3.0 (https://creativecommons.org/licenses/by/3.0/).
  Modified by GamepadLab, from ${family.source}:
${family.changes.map((c) => `  - ${c}`).join('\n')}
  Generated by scripts/build-controller-art.mjs; see ASSETS_LICENSE.md.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${family.viewBox}" data-art="${family.art}" stroke-miterlimit="10">
${lines.join('\n')}
</svg>
`;
  writeFileSync(`${ROOT}/${family.out}`, out);
  console.log(
    `${family.out}: ${src.length - dropped.length} source elements, ${dropped.length} dropped`,
  );
}

// ---- GamepadLab's own parts -------------------------------------------------

/** L2/R2-style analog gauge (the front views do not show the triggers). */
const gauge = (id, label, x, y, w = 280, h = 64) => `<g id="${id}" class="gl-trigger">
  <rect class="gl-part" x="${x}" y="${y}" width="${w}" height="${h}" rx="${h / 2}" stroke-width="7"/>
  <rect id="${id}-fill" class="gl-gauge-fill" x="${x + 10}" y="${y + 10}" width="${w - 20}" height="${h - 20}" rx="${(h - 20) / 2}"/>
  <text class="gl-label" x="${x + w / 2}" y="${y + h / 2}" font-size="34" text-anchor="middle" dominant-baseline="central">${label} <tspan id="${id}-value">0%</tspan></text>
</g>`;

/** Lights one direction of a one-piece D-pad drawing. */
const arm = (id, x, y, w, h) =>
  `<rect id="${id}" class="gl-hit" x="${x}" y="${y}" width="${w}" height="${h}" rx="14"/>`;

/** D-pad arms over a "+" whose bounding box is (x0, y0)–(x1, y1). */
function arms(x0, y0, x1, y1, width) {
  const cx = (x0 + x1) / 2;
  const cy = (y0 + y1) / 2;
  const half = width / 2;
  const reach = (x1 - x0) / 2 - half;
  return [
    arm('dpad-up', cx - half, y0, width, reach),
    arm('dpad-down', cx - half, y1 - reach, width, reach),
    arm('dpad-left', x0, cy - half, reach, width),
    arm('dpad-right', x1 - reach, cy - half, reach, width),
  ].join('\n');
}

/** Small labelled pill for extra buttons (DualSense Edge Fn, Elite paddles). */
const pill = (id, label, x, y, w, h, back = false) => `<g id="${id}" class="gl-extra">
  <rect class="gl-part${back ? ' gl-back' : ''}" x="${x}" y="${y}" width="${w}" height="${h}" rx="${h / 2}" stroke-width="6"/>
  <text class="gl-label" x="${x + w / 2}" y="${y + h / 2}" font-size="26" text-anchor="middle" dominant-baseline="central">${label}</text>
</g>`;

